export function formatTime(seconds){
  if(!Number.isFinite(seconds)||seconds<0)return '00:00';
  const t=Math.floor(seconds),h=Math.floor(t/3600),m=Math.floor(t%3600/60),s=t%60;
  return (h?String(h)+':':'')+String(m).padStart(2,'0')+':'+String(s).padStart(2,'0');
}
export function formatBytes(bytes){
  if(!Number.isFinite(bytes)||bytes<0)return '—';
  const n=bytes>=1048576?bytes/1048576:bytes>=1024?bytes/1024:bytes;
  return (n>=10?n.toFixed(0):n.toFixed(1))+' '+(bytes>=1048576?'MiB':bytes>=1024?'KiB':'B');
}
export function clampRange(start,end,duration,minGap=.1){
  const max=Number.isFinite(duration)&&duration>0?duration:0;
  if(max<minGap)return {start:0,end:max};
  const s=Math.max(0,Math.min(Number(start)||0,max-minGap));
  const e=Math.max(s+minGap,Math.min(Number(end)||max,max));
  return {start:Math.round(s*100)/100,end:Math.round(e*100)/100};
}
export function safeBase(name){
  return String(name||'clip').replace(/\.[^/.]+$/,'').normalize('NFKC').replace(/[^a-z0-9çğıöşü _-]/gi,'-').replace(/\s+/g,'-').replace(/-+/g,'-').slice(0,70).replace(/^-|-$/g,'')||'clip';
}
